CREATE   VIEW [dbo].[vw_dim_lot_active]
AS SELECT l1.[lot_guid],
			l1.[project_id],
			l1.[lot_id],
			l1.[lot_label],
			l1.[lot_number],
			l1.[street],
			l1.[street2],
			l1.[suite],
			l1.[city],
			l1.[state],
			l1.[zip],
			l1.[lot_status],
			l1.[lot_type],
			l1.[permit_date],
			l1.[release_date],
			l1.[takedown_date],
			l1.[lot_transfer_date],
			l1.[loan_status],
			l1.[notes_1],
			l1.[notes_2],
			l1.[plan_code],
			l1.[plan_description],
			l1.[elevation],
			l1.[base_square_footage],
			[lot_premium] = jp.baselotprice,
			l1.[revised_close_date],
			l1.[close_date],
			l1.[is_backlog],
			l1.[is_closed],
			l1.[is_spec],
			l1.[is_model],
			l1.[is_owned],
			l1.[is_started],
			l1.[is_completed],
			l1.[sold_not_started],
			l1.[close_reporting_date],
			l1.[sd_lot_id],
			l1.[is_soft_cost_lot],
			l1.[shell_lot],
			l1.[exclude_from_reporting],
			l1.[exclude_reason],
			l1.[lastmoddatetime],
			l1.[effective_start_date],
			l1.[effective_end_date],
			l1.[record_hash_key],
			l1.[is_active],
			l1.[is_deleted],
			l1.[created_date],
			l1.[created_by],
			l1.[created_job_run_id]
FROM [EDW_Silver].[dbo].[dim_lot] l1
	INNER JOIN HBLive.rems.jobphase jp ON
		jp.projid = l1.project_id
		AND jp.phase = l1.lot_number
WHERE l1.is_active = 'Y'