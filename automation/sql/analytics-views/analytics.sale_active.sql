			s1.[effective_end_date],
			s1.[record_hash_key],
			s1.[is_active],
			s1.[is_deleted],
			s1.[created_date],
			s1.[created_by],
			s1.[created_job_run_id]
FROM [transform].[sale] s1
INNER JOIN [transform].[lot] l1
    ON s1.lot_id = l1.lot_id
WHERE 
    s1.is_active = 'Y' 
    AND l1.is_active = 'Y'
    AND l1.exclude_from_reporting = 0

