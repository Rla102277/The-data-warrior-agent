			s1.[city],
			s1.[state],
			s1.[sqft],
			s1.[contingency_descr],
			s1.[contingency_expiry],
			s1.[buyer_name],
			s1.[buyer_email],
			s1.[buyer_cell_phone],
			s1.[buyer_home_phone],
			s1.[buyer_work_phone],
			s1.[cobuyer_names],
			s1.[sales_agent],
			s1.[sales_agent_email],
			s1.[sales_agent_cell_phone],
			s1.[sales_agent_home_phone],
			s1.[sales_agent_work_phone],
			s1.[realtor_name],
			s1.[realtor_email],
