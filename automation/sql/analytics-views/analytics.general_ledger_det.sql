			fgl1.[posting_date],
			fgl1.[memo_1],
			fgl1.[memo_2],
			fgl1.[amount],
			fgl1.[lot_id],
			fgl1.[major_code],
			fgl1.[minor_code],
			fgl1.[program_code],
			fgl1.[source_program_code],
			fgl1.[gl_created_by],
			fgl1.[gl_created_date],
